import httpx
from fastapi import Request, Response

from starlette.datastructures import Headers

from skeleton.infrastructure.gateway.src.schemas import UpstreamRequest
from skeleton.infrastructure.gateway.src.lifespan import HTTPAsyncClientManager
from skeleton.infrastructure.gateway.src.headers import HOP_BY_HOP_HEADERS

# talks directly to client &
# sends AsyncioClient.request()
class ProxyClient:
    
    def __init__(self, manager: HTTPAsyncClientManager):
        self.manager = manager

    @property
    def client(self):
        return self.manager.client

    def filter_hop_by_hop_headers(self, h: Headers) -> dict:
        
        headers = dict(h)

        # httpx auto regenerates host header from
        headers.pop("host", None)

        connection = headers.get("connection")

        if connection:
            for header in connection.split(","):
                headers.pop(header.strip().lower(), None)

        for header in HOP_BY_HOP_HEADERS:
            headers.pop(header.lower(), None)

        return headers

    async def request(self, clientRequest: UpstreamRequest):

        request: Request = clientRequest.request
        
        headers = self.filter_hop_by_hop_headers(
            clientRequest.request.headers
        )

        # host regenerated by upstream target!
        url = httpx.URL(clientRequest.target)
        headers["host"] = (
            f"{url.host}:{url.port}"
            if url.port else url.host
        )
        # print(json.dumps(headers, indent=4))

        # faster, once connected!
        upstream_response = await self.client.request(
            method=request.method,
            url=clientRequest.target,
            headers=headers,
            # stream body in chunks!
            content=await request.body()
        )

        return Response(
            content=upstream_response.content,
            status_code=upstream_response.status_code,
            headers=dict(upstream_response.headers)
        )
